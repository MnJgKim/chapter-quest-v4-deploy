CREATE OR REPLACE FUNCTION public.cq_v4_reread_on_submission()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE v_questions jsonb;v_key jsonb;v_answers jsonb:=new.answers->'answers';v_total integer:=0;v_correct integer:=0;v_i integer;v_q jsonb;v_expected jsonb;v_actual text;v_e text;
BEGIN
 SELECT act.questions,req.answer_key INTO v_questions,v_key
 FROM public.cq_v4_activities act
 JOIN public.cq_v4_pdf_chapters c ON c.chapter_id=act.chapter_uuid
 JOIN public.cq_v4_approval_requests req ON req.id=act.approval_id AND req.chapter_uuid=act.chapter_uuid
 AND req.parent_user_id=c.parent_user_id AND req.content_hash=act.approval_hash AND req.questions=act.questions
 WHERE act.chapter_uuid=new.chapter_uuid AND act.published_at IS NOT NULL AND act.approval_hash IS NOT NULL;
 IF jsonb_typeof(v_questions) IS DISTINCT FROM 'array' OR jsonb_typeof(v_key) IS DISTINCT FROM 'array'
 OR jsonb_typeof(v_answers) IS DISTINCT FROM 'array' THEN RETURN new; END IF;
 IF jsonb_array_length(v_questions)=0 OR jsonb_array_length(v_questions)<>jsonb_array_length(v_key)
 OR jsonb_array_length(v_questions)<>jsonb_array_length(v_answers) THEN RETURN new; END IF;
 FOR v_i IN 0..jsonb_array_length(v_questions)-1 LOOP
   v_q:=v_questions->v_i;
   IF v_q->>'kind'='mc' THEN
     v_expected:=v_key->v_i;v_e:=v_expected #>> '{}';v_actual:=v_answers->>v_i;
     IF jsonb_typeof(v_q->'options') IS DISTINCT FROM 'array'
       OR jsonb_typeof(v_expected) IS DISTINCT FROM 'number'
       OR COALESCE(v_e !~ '^(0|[1-9][0-9]{0,8})$',true)
       OR v_e::integer>=jsonb_array_length(v_q->'options')
     THEN RETURN new; END IF;
     v_total:=v_total+1;
     IF v_actual IS NOT NULL AND pg_catalog.btrim(v_actual)='' THEN CONTINUE; END IF;
     IF COALESCE(v_actual !~ '^(0|[1-9][0-9]{0,8})
     IF v_actual=v_e THEN v_correct:=v_correct+1; END IF;
   END IF;
 END LOOP;
 IF v_total>0 THEN
 INSERT INTO public.cq_v4_reread_progress(chapter_uuid,child_user_id,required)
 VALUES(new.chapter_uuid,new.child_user_id,(v_correct*10<v_total*7))
 ON CONFLICT DO NOTHING;
 END IF;
 RETURN new;
END;$function$;

